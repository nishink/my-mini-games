export function calculateHints(solution) {
    const rows = solution.length;
    const cols = solution[0].length;

    const rowHints = [];
    for (let r = 0; r < rows; r++) {
        const hints = [];
        let count = 0;
        for (let c = 0; c < cols; c++) {
            if (solution[r][c] === 1) {
                count++;
            } else if (count > 0) {
                hints.push(count);
                count = 0;
            }
        }
        if (count > 0) hints.push(count);
        if (hints.length === 0) hints.push(0);
        rowHints.push(hints);
    }

    const colHints = [];
    for (let c = 0; c < cols; c++) {
        const hints = [];
        let count = 0;
        for (let r = 0; r < rows; r++) {
            if (solution[r][c] === 1) {
                count++;
            } else if (count > 0) {
                hints.push(count);
                count = 0;
            }
        }
        if (count > 0) hints.push(count);
        if (hints.length === 0) hints.push(0);
        colHints.push(hints);
    }

    return { rowHints, colHints };
}
